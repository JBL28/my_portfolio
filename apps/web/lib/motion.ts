/**
 * Motion 공통 토큰(01_설계.md 5.3, 5.5).
 *
 * 값을 컴포넌트마다 흩어놓으면 "전환/피드백 목적의 절제된 애니메이션"이라는 5.5의
 * 톤이 금방 무너지므로 한 곳에 모은다. 5.3이 정한 "과하지 않게 200ms 내외"가 상한이고,
 * **애니메이션이 가독성을 해치지 않는다**는 것이 그보다 위의 원칙이다. 그래서:
 *
 * - 이동량은 6~12px로 제한한다. 이보다 크면 읽던 줄을 눈이 다시 찾아야 한다.
 * - 본문 텍스트(프로젝트 카드·섹션 등 "읽기 위해 온" 콘텐츠)에는 등장 애니메이션을
 *   걸지 않는다. 스크롤에 맞춰 글이 늦게 나타나면 읽기가 지연된다.
 * - 애니메이션 대상은 "상태가 바뀌었다는 사실"을 알려야 하는 UI(모달, 새 메시지,
 *   카운터, 토글)로 한정한다.
 */

/** 5.3의 "200ms 내외"를 상한으로 둔 지속시간(초). */
export const DURATION = {
  /** 토글·아이콘 등 즉각적인 피드백. */
  fast: 0.15,
  /** 모달·패널 전환의 기준값. */
  base: 0.22,
  /** 본문 콘텐츠 등장(components/ui/Reveal.tsx). */
  reveal: 0.28,
} as const;

/**
 * 목록을 순차로 띄울 때의 항목 간 지연(초). 60ms를 넘기면 아래쪽 항목이 눈에 띄게
 * 늦어져 "읽으려는데 아직 안 떴다"가 된다.
 */
export const STAGGER = 0.06;

/**
 * 감속(ease-out) 곡선. 시작은 빠르고 끝에서 부드럽게 멎는다 — 튕김(overshoot)이 없어
 * 무채색·컴팩트 톤을 해치지 않으면서도 "움직였다"는 인지는 남는다.
 */
export const EASE = [0.22, 1, 0.36, 1] as const;

/**
 * 공통 진입 모션. y 이동을 6px로 억제해 텍스트 가독성을 해치지 않는 선을 지킨다.
 * (모달처럼 더 분명한 전환이 필요한 곳은 각자 값을 키운다.)
 */
export const RISE = {
  initial: { opacity: 0, y: 6 },
  animate: { opacity: 1, y: 0 },
} as const;
